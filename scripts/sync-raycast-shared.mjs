#!/usr/bin/env node
import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SHARED_DIR = 'raycast/src/shared';
const BINDING_ROOTS = ['TrackInfo', 'PlaylistInfo'];
const HEADER = '// Generated by scripts/sync-raycast-shared.mjs from the desktop app. Do not edit.\n\n';

const COPIES = [
  { from: 'src/lib/remote-protocol.ts', to: 'remote-protocol.ts', rewrites: [["'@/bindings'", "'./bindings'"]] },
  { from: 'src/lib/selections.ts', to: 'selections.ts', rewrites: [] },
  { from: 'src-remote/lib/trackMapping.ts', to: 'trackMapping.ts', rewrites: [["'@/lib/remote-protocol'", "'./remote-protocol'"]] },
];

export function splitTypeDeclarations(source) {
  const declarations = new Map();
  const boundaries = [...source.matchAll(/^(?:export |import |const |let |function |class |type |declare )/gm)].map((m) => m.index);
  for (const match of source.matchAll(/^export type (\w+)\b/gm)) {
    const end = boundaries.find((index) => index > match.index) ?? source.length;
    declarations.set(match[1], source.slice(match.index, end).trimEnd());
  }
  return declarations;
}

export function extractTypes(source, roots) {
  const declarations = splitTypeDeclarations(source);
  const included = new Set();
  const pending = [...roots];
  while (pending.length > 0) {
    const name = pending.pop();
    if (included.has(name)) continue;
    const declaration = declarations.get(name);
    if (!declaration) throw new Error(`Type ${name} not found in bindings`);
    included.add(name);
    const body = declaration.replace(/\/\*\*[\s\S]*?\*\//g, '').slice(`export type ${name}`.length);
    for (const [identifier] of body.matchAll(/\b[A-Z]\w*\b/g)) {
      if (declarations.has(identifier)) pending.push(identifier);
    }
  }
  return (
    [...included]
      .sort()
      .map((name) => declarations.get(name))
      .join('\n\n') + '\n'
  );
}

function applyRewrites(content, rewrites, from) {
  return rewrites.reduce((result, [search, replacement]) => {
    if (!result.includes(search)) throw new Error(`${from}: expected import ${search} not found`);
    return result.replaceAll(search, replacement);
  }, content);
}

export function buildSharedFiles(root = ROOT) {
  const read = (file) => readFileSync(path.join(root, file), 'utf8');
  const files = new Map();
  files.set('bindings.ts', HEADER + extractTypes(read('src/bindings.ts'), BINDING_ROOTS));
  for (const { from, to, rewrites } of COPIES) {
    files.set(to, HEADER + applyRewrites(read(from), rewrites, from));
  }
  return files;
}

function staleFiles(root, files) {
  return [...files].filter(([name, content]) => {
    const target = path.join(root, SHARED_DIR, name);
    return !existsSync(target) || readFileSync(target, 'utf8') !== content;
  });
}

function main() {
  const check = process.argv.includes('--check');
  const files = buildSharedFiles();
  const stale = staleFiles(ROOT, files);
  if (check) {
    if (stale.length === 0) {
      console.log(`${SHARED_DIR} is up to date`);
      return;
    }
    console.error(`${SHARED_DIR} is out of date: ${stale.map(([name]) => name).join(', ')}`);
    console.error('Run: npm run sync:raycast');
    process.exitCode = 1;
    return;
  }
  mkdirSync(path.join(ROOT, SHARED_DIR), { recursive: true });
  for (const [name, content] of stale) {
    writeFileSync(path.join(ROOT, SHARED_DIR, name), content);
    console.log(`wrote ${SHARED_DIR}/${name}`);
  }
  if (stale.length === 0) console.log(`${SHARED_DIR} already up to date`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
